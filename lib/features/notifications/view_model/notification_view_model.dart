import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:libro/core/models/notification_model.dart';
import 'package:libro/core/repositories/notification_repository.dart';
import 'package:libro/shared/providers/firebase_providers.dart';

// 1. The Stream of Notifications (FIXED: Direct Query to ensure filtering)
final notificationsStreamProvider = StreamProvider<List<NotificationModel>>((
  ref,
) {
  // Watch the Auth State directly to handle login/logout updates
  final user = ref.watch(authStateChangesProvider).value;

  if (user == null) {
    return Stream.value([]);
  }

  // Direct Firestore query to guarantee filtering by 'userId'
  return FirebaseFirestore.instance
      .collection('notifications')
      .where('userId', isEqualTo: user.uid) // <--- The Critical Fix
      .orderBy('timestamp', descending: true)
      .snapshots()
      .map((snapshot) {
        return snapshot.docs
            .map((doc) {
              try {
                // Assuming NotificationModel has a fromMap factory
                return NotificationModel.fromMap(doc.data(), doc.id);
              } catch (e) {
                return null;
              }
            })
            .where((e) => e != null)
            .cast<NotificationModel>()
            .toList();
      });
});

// 2. Unread Notification Count
final unreadNotificationCountProvider = Provider<int>((ref) {
  final notificationsAsync = ref.watch(notificationsStreamProvider);
  return notificationsAsync.when(
    data: (list) => list.where((n) => !n.isRead).length,
    loading: () => 0,
    error: (_, __) => 0,
  );
});

class NotificationViewModel {
  final NotificationRepository _repo;

  NotificationViewModel(this._repo);

  Future<void> markAsRead(String id) async {
    await _repo.markAsRead(id);
  }

  // --- GENERIC SEND METHOD ---
  Future<void> _sendNotification({
    required String toUserId,
    required String title,
    required String body,
    required String
    type, // 'order', 'subscription', 'book_upload', 'store', 'security'
  }) async {
    final notif = NotificationModel(
      id: '', // Auto-generated by repo/firestore
      userId: toUserId,
      title: title,
      body: body,
      type: type,
      relatedId: '',
      timestamp: DateTime.now(),
      isRead: false,
    );
    await _repo.createNotification(notif);
  }

  // --- SPECIFIC NOTIFICATION TRIGGERS ---

  // 1. Book Uploaded
  Future<void> notifyBookUploaded({
    required String userId,
    required String bookTitle,
    required String transactionType,
  }) async {
    await _sendNotification(
      toUserId: userId,
      title: "Book Uploaded",
      body: "Your book '$bookTitle' is now listed for $transactionType.",
      type: "book_upload",
    );
  }

  // 2. Subscription Paid
  Future<void> notifySubscriptionPaid({
    required String userId,
    required String planName,
    required double amount,
  }) async {
    await _sendNotification(
      toUserId: userId,
      title: "Subscription Active",
      body: "Payment of Rs. $amount for $planName was successful.",
      type: "subscription",
    );
  }

  // 3. Store Created
  Future<void> notifyStoreCreated({
    required String userId,
    required String storeName,
  }) async {
    await _sendNotification(
      toUserId: userId,
      title: "Store Created",
      body: "Your store '$storeName' is now live.",
      type: "store",
    );
  }
}

// 3. The ViewModel Provider
final notificationViewModelProvider = Provider<NotificationViewModel>((ref) {
  final repo = ref.watch(notificationRepositoryProvider);
  return NotificationViewModel(repo);
});
